"""Capture several entries in one isolated game, validating each against its CPU return."""
import collections
import datetime
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
import time
import uuid

import psutil

from .common import OUT, REPO, PAGE, scenario, name_of
from .debugger import Debugger, LiveProvider, state_of
from .machine import Machine
from .compare import context_result, difference
from .store import PageStore, write_capture, write_run
from .pe import free_gap


def log(s):
    print(s, flush=True)


def game_in_slot(slot, since=0):
    for p in psutil.process_iter(['name', 'cmdline', 'create_time']):
        try:
            if p.info['name'] == 'SimCity 4.exe' and p.info['create_time'] >= since and any(
                    f'slot{slot:02d}' in a for a in p.info['cmdline'] or []):
                return p
        except psutil.Error:
            pass


def capture(args, targets):
    if args.slot not in (9, 10):
        raise ValueError('capture uses only slots 9 and 10')
    if game_in_slot(args.slot):
        raise ValueError(f'slot {args.slot} already has a game')
    disk = shutil.disk_usage(REPO)
    if disk.used / disk.total >= .85:
        raise ValueError('disk is at least 85% used')
    OUT.mkdir(parents=True, exist_ok=True)
    # Keep all reference artifacts generated by the harness under prove.
    pin = json.loads((REPO / 'build-runs/golden/reference.json').read_text())
    dll = REPO / 'build-runs/golden-inputs' / (pin['dll_sha256'] + '.dll')
    if hashlib.sha256(dll.read_bytes()).hexdigest() != pin['dll_sha256']:
        raise ValueError('pinned DLL hash mismatch')
    for dst in (OUT / 'golden', OUT / 'golden-inputs'):
        dst.mkdir(exist_ok=True)
    (OUT / 'golden/reference.json').write_text(json.dumps(pin))
    staged = OUT / 'golden-inputs' / dll.name
    if not staged.exists():
        shutil.copyfile(dll, staged)
    scen = scenario(args.scenario)
    run = datetime.datetime.now().strftime('%Y%m%d-%H%M%S-') + uuid.uuid4().hex[:6]
    cmd = [sys.executable, str(REPO / 'tools/golden.py'), 'record', '--region', scen['region'],
           '--city', scen['city'], '--until', scen['end'], '--backend', 'direct', '--slot', str(args.slot),
           '--seconds', str(min(3600, args.timeout + 120)), '--schedule', 'fixed', '--output', str(OUT), '--rerun']
    if scen['script'] != '-':
        cmd += ['--script', str(REPO / scen['script'])]
    env = dict(os.environ, GOLDEN_INI_EXTRA='autotest_stall_grace_ms = 120000')
    start = time.time()
    counts, passed, failed = collections.Counter(), collections.Counter(), collections.Counter()
    store = PageStore()
    logfile = (OUT / f'{run}-game.log').open('w')
    golden = subprocess.Popen(cmd, cwd=REPO, env=env, stdout=logfile, stderr=subprocess.STDOUT)
    game = dbg = None
    records = []
    try:
        while time.time()-start < 150 and golden.poll() is None:
            game = game_in_slot(args.slot, start-1)
            if game:
                break
            time.sleep(.2)
        if game is None:
            raise ValueError(f'game did not start; see {logfile.name}')
        dbg = Debugger(game.pid, log=log)
        dbg.targets = set(targets)

        def on_entry(tid, addr, ctx):
            if counts[addr] >= args.hits:
                return False
            counts[addr] += 1
            proc = dbg.proc
            state = state_of(ctx, proc.fs_base(tid, struct.unpack_from('<I', ctx, 0x90)[0]), tid)
            regs = state['regs']
            ret = struct.unpack('<I', proc.read(regs['esp'], 4))[0]
            regions = proc.regions()
            gdt = free_gap([regions], PAGE)
            teb = proc.read(state['fs_base'], 12)
            stack_hi, stack_lo = struct.unpack_from('<II', teb, 4)
            wow = [r for r in regions if r[5].lower().endswith('wow64cpu.dll')]
            sysrange = [min(r[0] for r in wow), max(r[0]+r[1] for r in wow)] if wow else None
            machine = Machine(state, LiveProvider(proc), gdt=gdt, syscall_range=sysrange)
            machine.ensure(max(stack_lo, (regs['esp'] & -PAGE)-PAGE),
                           min(stack_hi, (regs['esp'] & -PAGE)+PAGE*3)-max(stack_lo, (regs['esp'] & -PAGE)-PAGE))
            original = machine.run(addr, ret, regs['esp'], timeout=args.replay_timeout)
            dirty = machine.dirty()
            rec = dict(version=1, function=addr, scenario=args.scenario, run=run, hit=counts[addr],
                       entry=state, ret=ret, stack=[stack_lo, stack_hi], gdt=gdt, syscall_range=sysrange,
                       regions=regions, pinned=pin, replay_seconds=original['seconds'])
            log(f'{addr:08x} {name_of(addr)} hit {counts[addr]}: replay {original["seconds"]:.4f}s, '
                f'{len(machine.entry)} pages' + (f', {original["err"]}' if original['err'] else ''))
            dbg.wait_exit(dict(rec=rec, machine=machine, original=original, dirty=dirty),
                          tid, ret, regs['esp'])
            return counts[addr] < args.hits

        def on_exit(tid, pending, ctx):
            rec, m, original = pending['rec'], pending['machine'], pending['original']
            cpu = state_of(ctx, rec['entry']['fs_base'], tid)
            initial = {p: b for p, b in m.entry.items() if p not in m.static}
            actual = {}
            unreadable = []
            for p, b in initial.items():
                end = dbg.proc.page(p)
                if end is None:
                    unreadable.append(p)
                elif end != b:
                    actual[p] = end
            # The kernel updates these shared timestamps even while all game
            # threads are stopped. Excuse only the documented clock fields,
            # and log each differing byte with both values in the hit record.
            clock_rules = []
            # The emulator's own pages (GDT and its entry frame, port images) exist only in the replay.
            emulated = {p: b for p, b in pending['dirty'].items() if p not in m.static}
            compared_actual = dict(actual)
            cp = 0x7ffe0000
            if cp in initial:
                a = bytearray(actual.get(cp, initial[cp]))
                b = bytearray(emulated.get(cp, initial[cp]))
                for lo, hi, label in ((0, 4, 'TickCountLowDeprecated'), (8, 32, 'InterruptTime/SystemTime'),
                                      (0x320, 0x330, 'TickCount'),
                                      (0x340, 0x358, 'TimeUpdateLock/BaselineQpc'),
                                      (0x3b0, 0x3c0, 'InterruptTimeBias/QpcBias')):
                    for i in range(lo, hi):
                        if a[i] != b[i]:
                            clock_rules.append(dict(rule='kernel shared timestamp', field=label,
                                                    address=f'{cp+i:08x}', cpu=a[i], replay=b[i]))
                        a[i] = b[i] = initial[cp][i]
                compared_actual[cp], emulated[cp] = bytes(a), bytes(b)
            diff = difference(context_result(cpu), original, ('al', 'ah', 'eaxhi', 'edx', 'ecx'),
                              compared_actual, emulated, initial, rec['stack'])
            if unreadable:
                diff = dict(field='CPU exit page unavailable', addresses=unreadable)
            if pending.get('others_resumed'):
                diff = dict(field='other threads resumed while function was running')
            # Repeat from the identical entry, with fixed external inputs.
            m.restore(pending['dirty'])
            again = m.run(rec['function'], rec['ret'], rec['entry']['regs']['esp'], timeout=args.replay_timeout)
            repeat_diff = None
            if ({k: v for k, v in original.items() if k != 'seconds'} !=
                    {k: v for k, v in again.items() if k != 'seconds'} or pending['dirty'] != m.dirty()):
                repeat_diff = dict(field='replay outcome or memory differs')
            if repeat_diff:
                diff = dict(field='nondeterministic replay', detail=repeat_diff)
            pages = sorted(initial)
            rec['pages'] = dict(zip(map(str, pages), store.put_many(initial[p] for p in pages)))
            changed = sorted(actual)
            rec['exit_pages'] = dict(zip(map(str, changed), store.put_many(actual[p] for p in changed)))
            rec['exit'] = cpu
            rec['validation'] = dict(valid=diff is None, difference=diff, clock_rules=clock_rules,
                                     compared_pages=len(initial), clock_reads=original['clock_reads'])
            path = write_capture(rec)
            records.append(str(path))
            (passed if diff is None else failed)[rec['function']] += 1
            log(f'  validation {"PASS" if diff is None else "FAIL " + json.dumps(diff)}; {path.name}')

        dbg.attach()
        status = dbg.loop(on_entry, on_exit, until=lambda: all(counts[a] >= args.hits for a in targets),
                          timeout=args.timeout, hold=3)
        log(f'capture loop: {status}')
    finally:
        if dbg:
            for pending in dbg.exits:
                rec, m = pending['rec'], pending['machine']
                initial = {p: b for p, b in m.entry.items() if p not in m.static}
                pages = sorted(initial)
                rec['pages'] = dict(zip(map(str, pages), store.put_many(initial[p] for p in pages)))
                rec['exit_pages'], rec['exit'] = {}, None
                rec['validation'] = dict(valid=False, difference=dict(field='CPU return was not captured'), clock_rules=[])
                records.append(str(write_capture(rec)))
                failed[rec['function']] += 1
            dbg.detach()
            dbg.proc.close()
        if game:
            try:
                game.kill()
            except psutil.Error:
                pass
        try:
            golden.wait(timeout=30)
        except subprocess.TimeoutExpired:
            for p in psutil.Process(golden.pid).children(recursive=True):
                try:
                    p.kill()
                except psutil.Error:
                    pass
            golden.kill()
        logfile.close()
        meta = dict(run=run, scenario=args.scenario, slot=args.slot, pinned=pin, records=records,
                    counts=dict(counts), passed=dict(passed), failed=dict(failed), seconds=time.time()-start,
                    store_pages=store.stats()[0], store_compressed_bytes=store.stats()[1])
        write_run(run, meta)
        store.close()
    log(json.dumps({k: v for k, v in meta.items() if k != 'records'}))
    for a in targets:
        log(f'{a:08x}\t{name_of(a)}\t{counts[a]}\tvalid={passed[a]}\tinvalid={failed[a]}')
    return 0
